const TABLES: Record<Locale, Dict> = { it, en, fr, es, de, zh, ja }

let locale: Locale = 'en'

function matchLocale(tag: string): Locale | null {
  // Browsers use it-IT; some runtimes report it_IT — normalize before matching.
  const lower = tag.toLowerCase().replace(/_/g, '-')
  const primary = lower.split('-')[0] ?? ''
  if (primary === 'zh') return 'zh'
  if (primary === 'ja') return 'ja'
  if (primary === 'fr') return 'fr'
  if (primary === 'es') return 'es'
  if (primary === 'de') return 'de'
  if (primary === 'it') return 'it'
  if (primary === 'en') return 'en'
  return null
}

/** Pick UI language from browser settings (navigator.languages). */
export function detectLocale(languages: readonly string[] = navigator.languages ?? [navigator.language]): Locale {
  for (const tag of languages) {
    const hit = matchLocale(tag)
    if (hit) return hit
  }
  return 'en'
}

export function getLocale(): Locale {
  return locale
}

export function setLocale(next: Locale) {
  locale = next
  document.documentElement.lang = next === 'zh' ? 'zh-Hans' : next
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const table = TABLES[locale] ?? en
  let text = table[key] ?? en[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value))
    }
  }
  return text
}

/** Apply data-i18n / data-i18n-placeholder / data-i18n-aria-label under root. */
export function applyDomI18n(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n
    if (!key) return
    node.textContent = t(key)
  })
  root.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach((node) => {
    const key = node.dataset.i18nHtml
    if (!key) return
    node.innerHTML = t(key)
  })
  root.querySelectorAll<HTMLElement>('[data-i18n-placeholder]').forEach((node) => {
    const key = node.dataset.i18nPlaceholder
    if (!key) return
    if ('placeholder' in node) (node as HTMLInputElement).placeholder = t(key)
  })
  root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]').forEach((node) => {
    const key = node.dataset.i18nAriaLabel
    if (!key) return
    node.setAttribute('aria-label', t(key))
  })
  const title = document.querySelector('title')
  if (title) title.textContent = t('docTitle')
}

export function initI18n(): Locale {
  setLocale(detectLocale())
  applyDomI18n()
  return locale
}

export function localeTag(): string {
  return locale === 'zh' ? 'zh-CN' : locale
}
